import * as esbuild from "esbuild";
import { readFileSync, mkdirSync, writeFileSync } from "fs";

const result = await esbuild.build({
  entryPoints: ["assets/web/editor/editor.ts"],
  bundle: true,
  format: "iife",
  write: false,
  target: "es2020",
  minify: process.argv.includes("--minify"),
  logLevel: "info",
});

const script = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const template = readFileSync("assets/web/editor/index.html", "utf8");
const html = template.replace("<!--EDITOR_SCRIPT-->", () => `<script>\n${script}\n</script>`);

mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/editorHtml.ts",
  `// Generated by scripts/build-editor.mjs — do not edit.\nexport const EDITOR_HTML = ${JSON.stringify(html)};\n`
);
